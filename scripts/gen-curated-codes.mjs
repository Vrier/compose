/* ===========================================================================
   COMPOSE — curated unlock-code registry generator (S43).

     node scripts/gen-curated-codes.mjs [outPath]   (default: compose/curated-codes.json)

   DETERMINISTIC: code = the first 6 bytes of sha256("compose-curated:"+key),
   each byte mapped mod 32 into the unlock-code alphabet
   'abcdefghijkmnpqrstuvwxyz23456789' and uppercased (the same alphabet the
   server uses for instructor version codes). Intra-registry collisions
   resolve deterministically by re-hashing with ":1", ":2", … appended, in a
   fixed generation order (worksheets sorted, then chapter pages, then
   families). Re-running this script always reproduces the committed file
   byte-for-byte — test/server.mjs asserts exactly that.

   Keys: every compose/exercises/*.compose.json worksheet, every curated
   chapter page (from build/curated-map.mjs, e.g. cc/ch6), and the three
   families cc / hk / papers.

   The app embeds the registry at build time (window.COMPOSE_CURATED,
   build/assemble.mjs) and checks it BEFORE the server redeem API — curated
   codes therefore SHADOW instructor version codes. With ~70 curated codes in
   a 32^6 ≈ 1.07e9 space the odds a server-generated code collides with a
   curated one are negligible, and the shadowing direction is accepted.
   =========================================================================== */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { curatedTable } from '../build/curated-map.mjs';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = process.argv[2] || path.join(ROOT, 'compose', 'curated-codes.json');

const ALPHABET = 'abcdefghijkmnpqrstuvwxyz23456789'.toUpperCase();

const EX_DIR = path.join(ROOT, 'compose', 'exercises');
const wsKeys = fs.readdirSync(EX_DIR)
  .filter((f) => f.endsWith('.compose.json'))
  .map((f) => f.replace('.compose.json', ''))
  .sort((a, b) => a.localeCompare(b, 'en', { numeric: true }));

const titles = {};
for (const k of wsKeys) {
  try { titles[k] = JSON.parse(fs.readFileSync(path.join(EX_DIR, k + '.compose.json'), 'utf8')).title || k; }
  catch (e) { titles[k] = k; }
}

const curated = curatedTable(wsKeys);
const chapterPages = curated.filter((e) => e.path.includes('/'));
const familyPages = curated.filter((e) => !e.path.includes('/'));

const taken = new Set();
function codeFor(key) {
  for (let n = 0; ; n++) {
    const input = 'compose-curated:' + key + (n ? ':' + n : '');
    const h = crypto.createHash('sha256').update(input).digest();
    let code = '';
    for (let i = 0; i < 6; i++) code += ALPHABET[h[i] % 32];
    if (!taken.has(code)) { taken.add(code); return code; }
  }
}

/* Fixed generation order (worksheets → chapters → families) so collision
   fallbacks are stable across runs. */
const entries = [];
for (const k of wsKeys) {
  const page = chapterPages.find((e) => e.keys.includes(k)) || familyPages.find((e) => e.keys.includes(k)) || null;
  entries.push({
    code: codeFor(k), kind: 'worksheet', key: k, title: titles[k],
    url: page ? '/' + page.path + '/?ws=' + k : '/',
  });
}
for (const e of chapterPages) {
  const entry = { code: codeFor(e.path), kind: 'chapter', key: e.path, title: e.title, url: '/' + e.path + '/' };
  if (e.prefix) entry.prefix = e.prefix;
  entries.push(entry);
}
for (const e of familyPages) {
  entries.push({ code: codeFor(e.path), kind: 'family', key: e.path, title: e.title, url: '/' + e.path + '/' });
}

const out = {
  comment: 'Generated by scripts/gen-curated-codes.mjs — do NOT edit by hand; re-run the script. '
    + 'Deterministic codes: first 6 bytes of sha256("compose-curated:"+key), byte mod 32 into the unlock alphabet, uppercased; '
    + 'collisions re-hash with ":1", ":2", … in generation order. The app resolves these BEFORE the server redeem API, '
    + 'so curated codes shadow instructor version codes (accepted: ~70 codes in a 32^6 space).',
  entries,
};

fs.writeFileSync(OUT, JSON.stringify(out, null, 2) + '\n');
console.log('wrote ' + OUT + ' — ' + entries.length + ' entries ('
  + entries.filter((e) => e.kind === 'worksheet').length + ' worksheets, '
  + entries.filter((e) => e.kind === 'chapter').length + ' chapter pages, '
  + entries.filter((e) => e.kind === 'family').length + ' families)');
