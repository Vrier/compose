#!/usr/bin/env node
/* ===========================================================================
   COMPOSE: regenerate test/fixtures/linglib-rules.json from Linglib.

   1. Loads the real engine and solves every derivation in compose/exercises,
      collecting the pair of sister types at every binary node it completes.
   2. Writes those pairs as ComposeLean/LibPairs.lean (pairs over a sort Linglib
      lacks, such as the time sort i, are listed and left out).
   3. Runs Lean: Mathlib's cache, Linglib's release build, then
      ComposeLean/RuleOracle.lean, which evaluates Linglib's own rule
      definitions on a grid of types and on the library pairs.
   4. Writes the fixture test/linglib-rules.mjs reads, with Linglib's revision.

   Requires elan (it installs the Lean version in lean-toolchain). The first
   run downloads about 11 GB (Mathlib's compiled files, the toolchain and
   Linglib's release archive) and takes a few minutes; later runs take seconds.

   Usage (from anywhere):  node tools/linglib/regenerate.mjs [--no-lean]
     --no-lean  skip step 3 and rebuild the fixture from the last Lean output
   =========================================================================== */
import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(HERE, '..', '..');
const SRC = path.join(ROOT, 'compose');
const FIXTURE = path.join(ROOT, 'test', 'fixtures', 'linglib-rules.json');
const SHARED = new Set(['t', 'e', 's', 'v', 'n']);   // sorts COMPOSE and Linglib share

/* ---- 1. the engine and the library's sister-type pairs ------------------ */
globalThis.window = globalThis;
globalThis.document = { getElementById: () => null, createElement: () => ({ style: {}, appendChild() {} }), querySelector: () => null, addEventListener() {} };
globalThis.localStorage = { getItem: () => null, setItem() {}, removeItem() {} };
for (const f of ['engine.js', 'lcformat.js']) vm.runInThisContext(fs.readFileSync(path.join(SRC, f), 'utf8'), { filename: f });
const E = window.LC, F = window.LCFormat;

const tstr = (t) => (typeof t === 'string' ? t : t && t.from !== undefined ? '<' + tstr(t.from) + ',' + tstr(t.to) + '>' : '?');
const sorts = (s) => s.replace(/[<>,]/g, ' ').split(/\s+/).filter(Boolean);

const pairs = new Map();
const exDir = path.join(SRC, 'exercises');
for (const f of fs.readdirSync(exDir).filter((x) => x.endsWith('.compose.json')).sort()) {
  const set = F.parseFile(fs.readFileSync(path.join(exDir, f), 'utf8'), f);
  for (const g of set.groups) for (const p of g.problems) {
    let root; try { root = F.parseTree(p.tree); } catch { continue; }
    const sol = F.solveTree(root, set);
    (function walk(n) {
      const kids = (n.children || []).filter((c) => !(c.word && /^\d+$/.test(c.word)));
      if (kids.length === 2 && sol[kids[0].id] && sol[kids[1].id]) {
        const l = tstr(sol[kids[0].id].type), r = tstr(sol[kids[1].id].type);
        pairs.set(l + ' ' + r, { l, r });
      }
      (n.children || []).forEach(walk);
    })(root);
  }
}

/* ---- 2. ComposeLean/LibPairs.lean --------------------------------------- */
const LEAN_ATOM = { t: '.t', e: 'Ty.e', s: 'Ty.s', v: 'Ty.v', n: 'Ty.n' };
function leanTy(s) {
  let i = 0;
  const ty = () => {
    if (s[i] === '<') { i++; const a = ty(); i++; const b = ty(); i++; return '(Ty.fn ' + a + ' ' + b + ')'; }
    return LEAN_ATOM[s[i++]];
  };
  return ty();
}
const lib = [...pairs.values()].sort((a, b) => (a.l + ' ' + a.r).localeCompare(b.l + ' ' + b.r));
const shared = lib.filter((p) => sorts(p.l + ',' + p.r).every((a) => SHARED.has(a)));
const outside = lib.filter((p) => !shared.includes(p));
fs.writeFileSync(path.join(HERE, 'ComposeLean', 'LibPairs.lean'),
  'import Linglib.Semantics.Composition.Sorts\nopen Interpreter\n' +
  '/-- Sister-type pairs that occur in COMPOSE\'s curated library (generated by regenerate.mjs). -/\n' +
  'def libPairs : List (Ty Base × Ty Base) := [\n  ' +
  shared.map((p) => `(${leanTy(p.l)}, ${leanTy(p.r)})`).join(',\n  ') + '\n]\n');
console.log(`library: ${lib.length} sister-type pairs, ${shared.length} over shared sorts, ${outside.length} left out:`);
for (const p of outside) console.log('   ' + p.l + ' + ' + p.r);

/* ---- 3. Lean -------------------------------------------------------------- */
function lake(args) {
  console.log('\n$ lake ' + args.join(' '));
  const r = spawnSync('lake', args, { cwd: HERE, stdio: 'inherit', shell: process.platform === 'win32' });
  if (r.error || r.status !== 0) { console.error('lake ' + args[0] + ' failed' + (r.error ? ': ' + r.error.message : '')); process.exit(1); }
}
if (process.argv.includes('--no-lean')) {
  console.log('\n--no-lean: reusing the last oracle-grid.jsonl and oracle-lib.jsonl');
} else {
  lake(['exe', 'cache', 'get']);
  lake(['build', 'ComposeLean.LibPairs', 'Studies.HeimKratzer1998', 'Linglib.Semantics.Composition.Rules', 'Linglib.Semantics.Composition.Sorts']);
  lake(['env', 'lean', 'ComposeLean/RuleOracle.lean']);
}

/* ---- 4. the fixture ------------------------------------------------------ */
const rows = (f) => fs.readFileSync(path.join(HERE, f), 'utf8').trim().split('\n').map((l) => JSON.parse(l));
const grid = rows('oracle-grid.jsonl');
const libRows = rows('oracle-lib.jsonl');
const n = Math.round(Math.sqrt(grid.length));
if (n * n !== grid.length) throw new Error('grid is not square: ' + grid.length + ' rows');
const types = grid.slice(0, n).map((x) => x.r);
const gridRules = {};
for (const x of grid) if (x.rules.length) gridRules[x.l + ' ' + x.r] = x.rules;
const manifest = JSON.parse(fs.readFileSync(path.join(HERE, 'lake-manifest.json'), 'utf8'));
const ll = manifest.packages.find((p) => p.name === 'linglib');
const fixture = {
  about: 'Linglib\'s rule table, read by test/linglib-rules.mjs. Generated by tools/linglib/regenerate.mjs; do not edit by hand.',
  source: {
    linglib: ll.inputRev, linglibCommit: ll.rev, linglibUrl: ll.url,
    lean: fs.readFileSync(path.join(HERE, 'lean-toolchain'), 'utf8').trim(),
    generated: new Date().toISOString().slice(0, 10),
    rules: {
      fa: 'Interpreter.Application.fa', ba: 'Interpreter.Application.ba',
      pm: 'Interpreter.PredicateModification.pm',
      ifa: 'HeimKratzer1998.IntensionalApplication.ifa', iba: 'HeimKratzer1998.IntensionalApplication.iba',
      ei: 'Interpreter.EventIdentification (individuals e, eventualities v)',
    },
  },
  grid: { sorts: [...SHARED], maxSize: 5, types },
  gridRules,
  library: libRows.map((x) => ({ l: x.l, r: x.r, rules: x.rules })),
  libraryOutside: outside.map((p) => p.l + ' + ' + p.r),
};
// One line per grid entry and per library pair, so a regeneration diffs row by row.
const J = JSON.stringify;
fs.writeFileSync(FIXTURE, '{\n' +
  ` "about": ${J(fixture.about)},\n` +
  ` "source": ${J(fixture.source)},\n` +
  ` "grid": ${J(fixture.grid)},\n` +
  ' "gridRules": {\n' + Object.entries(gridRules).map(([k, v]) => `  ${J(k)}: ${J(v)}`).join(',\n') + '\n },\n' +
  ' "library": [\n' + fixture.library.map((x) => '  ' + J(x)).join(',\n') + '\n ],\n' +
  ` "libraryOutside": ${J(fixture.libraryOutside)}\n}\n`);
JSON.parse(fs.readFileSync(FIXTURE, 'utf8'));   // the hand-laid file must still be JSON
console.log(`\nwrote ${path.relative(ROOT, FIXTURE)}: ${types.length} grid types (${grid.length} pairs, ${Object.keys(gridRules).length} with a rule), ${libRows.length} library pairs; Linglib ${ll.inputRev} @ ${ll.rev.slice(0, 7)}`);
